const CONTEXT_TEXT = {
  home: "головний екран",
  bot: "картка бота",
  monitor: "розділ «Моніторинг» (стан серверних ботів)",
  chart: "ринок і графік",
  backtest: "бектести",
  risk: "ризики та ліміти",
  profile: "профіль",
};

/** Опис контексту, з якого користувач відкрив помічника. */
export function contextLine(ctx) {
  const c = ctx || { type: "home" };
  const parts = [CONTEXT_TEXT[c.type] || CONTEXT_TEXT.home];
  if (c.pair) parts.push(`пара ${c.pair}`);
  if (c.id) parts.push(`id бота ${c.id} (за потреби виклич get_bot_details або get_bot_state)`);
  return parts.join(", ");
}

